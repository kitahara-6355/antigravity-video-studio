def decode_line(line_bytes):
    """バイト列を文字列にデコードする。

    UTF-8、CP932の順で試行し、両方失敗した場合はエラー文字に置換してデコードします。

    Args:
        line_bytes (bytes | bytearray): デコード対象のバイト列。

    Returns:
        str: デコードされた文字列。

    Raises:
        TypeError: 引数が bytes または bytearray ではない場合。
    """
    if not isinstance(line_bytes, (bytes, bytearray)):
        raise TypeError("line_bytes must be bytes or bytearray")

    try:
        return line_bytes.decode("utf-8")
    except UnicodeDecodeError:
        pass
    try:
        return line_bytes.decode("cp932")
    except UnicodeDecodeError:
        pass
    return line_bytes.decode("utf-8", errors="replace")

